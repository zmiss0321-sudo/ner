export function getPinyinInitial(char: string): string {
  if (!char || char.length === 0) return "#";
  const first = char[0];

  // 非汉字直接返回原字符大写
  if (!/[一-鿿㐀-䶿]/.test(first)) {
    return /[a-zA-Z]/.test(first) ? first.toUpperCase() : "#";
  }

  // 先查特殊修正
  if (SPECIAL_MAP[first]) return SPECIAL_MAP[first];

  // 再查通用映射
  if (CHAR_MAP[first]) return CHAR_MAP[first];

  // 未覆盖字符：使用 Intl.Collator 拼音排序来估算首字母
  // 这是一个常见回退策略
  return estimateInitialFromCollation(first);
}

/**
 * 回退方案：使用 Intl.Collator 拼音排序，结合已知锚点字符估算首字母。
 * 这在字符映射表不完整时提供合理的近似结果。
 */
function estimateInitialFromCollation(char: string): string {
  // 拼音排序锚点 — 每个字母的典型起始字符
  const anchors: [string, string][] = [
    ["阿", "A"], ["八", "B"], ["擦", "C"], ["大", "D"], ["俄", "E"],
    ["发", "F"], ["嘎", "G"], ["哈", "H"], ["击", "J"], ["喀", "K"],
    ["拉", "L"], ["妈", "M"], ["拿", "N"], ["哦", "O"], ["趴", "P"],
    ["七", "Q"], ["然", "R"], ["撒", "S"], ["他", "T"], ["挖", "W"],
    ["西", "X"], ["压", "Y"], ["匝", "Z"],
  ];

  const collator = new Intl.Collator("zh-CN", { usage: "sort", sensitivity: "base" });

  for (let i = 0; i < anchors.length; i++) {
    const [anchorChar, initial] = anchors[i];
    if (collator.compare(char, anchorChar) < 0) {
      // char sorts before this anchor, so it belongs to previous initial
      return i > 0 ? anchors[i - 1][1] : "A";
    }
  }
  return "Z";
}

/**
 * 取文本的第一个汉字拼音首字母，大写
 */
export function getTextInitial(text: string): string {
  if (!text) return "#";
  // 跳过非汉字前缀
  for (const char of text) {
    if (/[一-鿿㐀-䶿]/.test(char)) {
      return getPinyinInitial(char);
    }
  }
  // 全是非汉字
  const first = text[0];
  return /[a-zA-Z]/.test(first) ? first.toUpperCase() : "#";
}

